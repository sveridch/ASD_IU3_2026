package ru.bmstu.lab01.task_2;

public class FirstIndex {
    public static int findFirstIndex(int[] array, int x) {
        if (array == null) {
            return -1;
        }

        for (int i = 0; i < array.length; i++) {
            if (array[i] == x) {
                return i;
            }
        }

        return -1;
    }
}